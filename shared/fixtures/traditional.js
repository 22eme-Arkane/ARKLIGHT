// Projecteurs traditionnels : tungstène (halogène) et HMI.
// Le tungstène se pilote par un gradateur (1 canal DMX) : le moteur simule la baisse de température
// de couleur et l'inertie du filament. Le HMI se gradue de 50 à 100 % par son ballast.
//
// Fiabilité des données (champ confidence) : « vérifié » = lu sur une page du fabricant ou d'un loueur ;
// « à vérifier » = trouvé seulement dans un résumé de recherche ; « estimé » = calculé (voir notes).
// Notes de recherche : docs/recherche/marques/notes-partielles.md

const DIMMER = [{ id: 'dim1', name: 'Gradateur (1 canal)', channels: [{ f: 'dimmer', label: 'Intensité' }] }];
const BALLAST = [{ id: 'hmi1', name: 'Ballast : gradation (1 canal)', channels: [{ f: 'dimmer', label: 'Gradation (50–100 %)' }] }];

/** Lux à 1 m depuis une mesure à d mètres (loi de l'inverse du carré). */
const at1m = (lux, d) => Math.round(lux * d * d);

const tungsten = ({ zoom, lamp, ...t }) => ({
  platform: 'generic',
  technology: 'tungsten',
  pixels: 1,
  lamp: { cct: 3200, ...lamp },
  watts: lamp.watts,
  beamAngle: zoom ? Math.round((zoom.min + zoom.max) / 2) : t.beamAngle,
  ...(zoom ? { zoom } : {}),
  output: { luxAt1m: zoom ? zoom.luxAt1m.at(-1)[1] : t.luxAt1m, estimated: t.confidence !== 'vérifié' },
  dmx: { modes: DIMMER },
  defaults: { settings: zoom ? { zoom: Math.round((zoom.min + zoom.max) / 2) } : {} },
  ...t,
});

